import type { BaseType } from "@ng-org/shex-orm";
import { useDeepSignal } from "@ng-org/alien-deepsignals/react";
import type { ShapeType } from "@ng-org/shex-orm";
import { useEffect, useMemo, useRef, useState } from "react";
import { normalizeConf } from "../../types.ts";
import {
    RdfOrmSubscription,
    RdfOrmSubscriptionFor,
} from "../../connector/RdfOrmSubscription.ts";
import type {
    DeepSignalSet,
    ReadOnlyArray,
    DeepSignal,
} from "@ng-org/alien-deepsignals";
import { RdfOrmConfig, SubscriptionData } from "../../utilTypes.ts";

/**
 * Hook to subscribe to RDF data in the graph database using a shape, see {@link ShapeType}.
 *
 * Establishes a 2-way binding with the returned data: Modifications to the data are automatically committed,
 * changes coming from the engine (or other components) cause an immediate rerender.
 *
 * @param shape The {@link ShapeType} the objects should have (generated by the shex-orm tool).
 * @param conf The config that can be a document nuri, {@link RdfOrmConfig} or undefined.
 * @returns A {@link UseShapeResult} with the orm objects or an empty set, if still loading.\
 *          If the conf is explicitly set to `undefined`, the returned data is `undefined` and `isLoading` is false.
 *
 * @example
 * ```tsx
 * function Expenses() {
 *     const { data: expenses, isLoading }: DeepSignal<Set<Expense>> = useShape(
 *         ExpenseShapeType,
 *         {
 *             graphs: ["<document NURI>"]
 *             orderBy: {dateOrPurchase: "desc"}
 *         }
 *     );
 *
 *     const createExpense = useCallback(
 *         () => {
 *             expenses.add({
 *                 "@graph": `<document NURI>`,
 *                 "@type": "did:ng:z:Expense",
 *                 "@id": "", // Assigns ID automatically, if set to "".
 *                 title: "New expense",
 *                 dateOfPurchase: obj.dateOfPurchase ?? new Date().toISOString(),
 *             });
 *         },
 *         [expenses]
 *     );
 *
 *     // Note that if you use `@id` (the subject IRI) as key and chose yourself, you need to ensure that it is unique within your scope.
 *     // If it is not (i.e. there are two graphs with the same subject), use the combination of `@graph` and `@id`.
 *
 *     return (
 *         <div>
 *             <button
 *                 onClick={() => createExpense({})}
 *             >
 *                 + Add expense
 *             </button>
 *             <div>
 *                 {isLoading && (
 *                     <p>
 *                         Loading...
 *                     </p>
 *                 )}
 *                 {expenses && expenses.length === 0 && (
 *                     <p>
 *                         No expenses yet.
 *                     </p>
 *                 )}
 *                 {expenses && expenses.length > 0 && (
 *                     expenses.map((expense) => (
 *                         // You can modify the expense's properties in the ExpenseCard component
 *                         // which will instantly trigger a rerender.
 *                         <ExpenseCard
 *                             key={expense["@id"]}
 *                             expense={expense}
 *                         />
 *                     ))
 *                 )}
 *             </div>
 *         </div>
 *     );
 * }
 * ```
 */
const useShape = <
    ST extends ShapeType<T>,
    const CONF extends RdfOrmConfig<T>,
    T extends BaseType = ST extends ShapeType<infer T_> ? T_ : never,
    SUBSCRIPTION_DATA = SubscriptionData<T, CONF>,
>(
    shape: ST,
    conf: CONF | string | undefined
): UseShapeResult<ST, CONF, T> => {
    const dependencies = [
        typeof conf,
        JSON.stringify((conf as CONF)?.graphs),
        JSON.stringify((conf as CONF)?.subjects),
        (conf as CONF)?.maxActivePages,
        (conf as CONF)?.pageSize,
        JSON.stringify((conf as CONF)?.orderBy),
    ];
    const parsedConf = useMemo(
        () => (!conf ? undefined : normalizeConf(conf)),
        dependencies
    );
    const [isReady, setIsReady] = useState(false);

    const prevOrmSubscription = useRef<
        undefined | RdfOrmSubscription<any, any>
    >(undefined);

    const ormSubscription = useMemo(() => {
        if (parsedConf === undefined) return undefined;
        if (prevOrmSubscription.current) prevOrmSubscription.current.close();

        const newOrmSubscription = RdfOrmSubscription.getOrCreate(
            shape,
            parsedConf
        );

        prevOrmSubscription.current = newOrmSubscription as any;

        return newOrmSubscription;
    }, dependencies);

    useEffect(() => {
        if (!ormSubscription) return;

        ormSubscription?.readyPromise.then(() => {
            setIsReady(true);
        });

        return () => {
            setIsReady(false);
            ormSubscription.close();
        };
    }, [ormSubscription]);

    // If no data has arrived or the scope is unset, use a dummy object
    // that won't be returned (useDeepSignal requires some kind of data).
    const state = useDeepSignal(
        ormSubscription && isReady ? ormSubscription.signalObject : emptyObject,
        {
            replaceProxiesInBranchOnChange: true,
        }
    );

    const nextPage =
        ormSubscription?.mode === "orderedPaginatedCumulative" ||
        ormSubscription?.mode === "orderedPaginatedSimple"
            ? // @ts-ignore
              ormSubscription.nextPage
            : undefined;
    const previousPage =
        ormSubscription?.mode === "orderedPaginatedSimple"
            ? // @ts-ignore
              ormSubscription.previousPage
            : undefined;

    // @ts-ignore
    return {
        data: (isReady ? state : undefined) as SUBSCRIPTION_DATA,
        isLoading: !ormSubscription ? false : ormSubscription.isReady,
        promise: ormSubscription?.readyPromise,
        subscription: ormSubscription,
        nextPage,
        previousPage,
    };
};

const emptyObject = {};

export default useShape;

type UseShapeResult_<
    ST extends ShapeType<any>,
    CONF extends RdfOrmConfig<T>,
    T extends BaseType,
    SUBSCRIPTION_DATA = SubscriptionData<T, CONF>,
> = {
    /**
     * Initializes loading of the next page.
     * This will update the data but you will not be called back on it.
     */
    nextPage: () => void;
    /**
     * Initializes loading of the previous page.
     * This will update the data but you will not be called back on it.
     */
    previousPage: () => void;
    /**
     * `true` when no data is available yet and `conf` is not `undefined`.
     *
     * It is *not* set to `true` when loading pages (through `nextPage()` or `previousPage()`.
     */
    isLoading: boolean;
    /**
     * The requested data, once loaded.
     * Depending on your orderBy config, this will either be a {@link DeepSignalSet}
     * or a [`DeepSignal<ReadOnlyArray>`]({@link DeepSignal}) (you can modify its properties and sub-objects though).
     *
     * This object is the value returned by {@link RdfOrmSubscription.signalObject} with the following exception:
     * The root is a proxy that is replaced on every rerender so that react knows that it changed.
     */
    data: SUBSCRIPTION_DATA | undefined;
    /**
     * A promise that resolves once the data is loaded.
     * Note that if `conf` is `undefined`, this property is `undefined`.
     */
    promise: CONF extends undefined ? undefined : Promise<SUBSCRIPTION_DATA>;
    /** The underlying {@link RdfOrmSubscription} through which the data is loaded. */
    subscription: CONF extends undefined
        ? undefined
        : RdfOrmSubscriptionFor<ST, CONF, T>;
};

export type UseShapeResult<
    ST extends ShapeType<any>,
    CONF extends RdfOrmConfig<T>,
    T extends BaseType,
> = undefined extends CONF["pageSize"]
    ? Omit<UseShapeResult_<ST, CONF, T>, "nextPage" | "previousPage"> // No pagination functions.
    : undefined extends CONF["maxActivePages"]
      ? Omit<UseShapeResult_<ST, CONF, T>, "previousPage"> // Only forward pagination without `maxActivePages`.
      : UseShapeResult_<ST, CONF, T>; // Forward and backwards pagination.
